// Every name constant of the gfx*.h headers is checked against the shipped pack: the constant must be the
// pack index of the entry with that name, and its typed id must resolve back to the same index.
// A swapped, shifted or missing constant fails here.

namespace {
struct NameConstant {
    std::string_view name;
    int index;
};

void checkTable(const std::string &packFile, const std::vector<NameConstant> &table)
{
    const std::string packPath = std::string(D2TM_SOURCE_DIR) + "/resources/bin/data/" + packFile;
    INFO("graphics pack not found: " << packPath);
    REQUIRE(std::filesystem::exists(packPath));

    auto *fakeRenderer = reinterpret_cast<SDL_Renderer *>(1);
    Graphics graphics(fakeRenderer, packPath);

    // no entry without a constant, no constant without an entry
    REQUIRE(static_cast<std::size_t>(graphics.getNumberOfFiles()) == table.size());

    const std::vector<std::string> names = graphics.getNames();
    for (const auto &[name, index] : table) {
        INFO(packFile << " " << name << " = " << index);
        REQUIRE(index >= 0);
        REQUIRE(static_cast<std::size_t>(index) < names.size());

        const SurfaceID surface = graphics.surfaceId(name);
        REQUIRE(surface != SurfaceID::invalid);
        REQUIRE(surface == toSurfaceID(index));
        REQUIRE(toPackIndex(surface) == index);

        const TextureID texture = graphics.textureId(name);
        REQUIRE(texture == toTextureID(index));
        REQUIRE(toPackIndex(texture) == index);
    }
}
}

